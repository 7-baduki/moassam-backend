package com.moassam.admin.adapter.persistence;

import com.moassam.admin.application.required.AdminDashboardQueryRepository;
import jakarta.persistence.EntityManager;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.orm.jpa.DataJpaTest;
import org.springframework.context.annotation.Import;
import org.springframework.test.context.ActiveProfiles;

import java.time.LocalDateTime;

import static org.assertj.core.api.Assertions.assertThat;

@ActiveProfiles("test")
@DataJpaTest
@Import(JdbcAdminDashboardQueryRepository.class)
class JdbcAdminDashboardQueryRepositoryTest {

    @Autowired
    private AdminDashboardQueryRepository repository;

    @Autowired
    private EntityManager entityManager;

    @BeforeEach
    void createAiUsageTable() {
        entityManager.createNativeQuery("""
                CREATE TABLE IF NOT EXISTS observation_generation_usages (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    correlation_id VARCHAR(36) NOT NULL,
                    user_id BIGINT NOT NULL,
                    operation VARCHAR(30) NOT NULL,
                    provider_status VARCHAR(30) NOT NULL,
                    business_status VARCHAR(30) NOT NULL,
                    model VARCHAR(100),
                    input_tokens BIGINT,
                    output_tokens BIGINT,
                    total_tokens BIGINT,
                    duration_ms BIGINT NOT NULL,
                    error_category VARCHAR(50),
                    occurred_at TIMESTAMP NOT NULL,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """).executeUpdate();
        entityManager.createNativeQuery("DELETE FROM observation_generation_usages").executeUpdate();
    }

    @Test
    void getAiUsageDoesNotCountPendingCallsAsFailures() {
        insertUsage("saved", "SUCCESS", "SAVED");
        insertUsage("provider-failed", "FAILED", "PROVIDER_FAILED");
        insertUsage("persistence-failed", "SUCCESS", "PERSISTENCE_FAILED");
        insertUsage("pending", "SUCCESS", "PENDING");

        var totals = repository.getAiUsage(
                LocalDateTime.of(2026, 10, 25, 0, 0),
                LocalDateTime.of(2026, 10, 26, 0, 0)
        );

        assertThat(totals.calls()).isEqualTo(4);
        assertThat(totals.successes()).isEqualTo(1);
        assertThat(totals.failures()).isEqualTo(2);
    }

    private void insertUsage(String correlationId, String providerStatus, String businessStatus) {
        entityManager.createNativeQuery("""
                        INSERT INTO observation_generation_usages(
                            correlation_id, user_id, operation, provider_status, business_status,
                            duration_ms, occurred_at
                        ) VALUES (:correlationId, 1, 'CREATE', :providerStatus, :businessStatus, 100, :occurredAt)
                        """)
                .setParameter("correlationId", correlationId)
                .setParameter("providerStatus", providerStatus)
                .setParameter("businessStatus", businessStatus)
                .setParameter("occurredAt", LocalDateTime.of(2026, 10, 25, 12, 0))
                .executeUpdate();
    }
}
