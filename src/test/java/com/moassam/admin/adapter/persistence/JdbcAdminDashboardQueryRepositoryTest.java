package com.moassam.admin.adapter.persistence;

import com.moassam.admin.application.required.AdminDashboardQueryRepository;
import jakarta.persistence.EntityManager;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.orm.jpa.DataJpaTest;
import org.springframework.context.annotation.Import;
import org.springframework.test.context.ActiveProfiles;

import java.time.LocalDate;
import java.time.LocalDateTime;

import static org.assertj.core.api.Assertions.assertThat;

@ActiveProfiles("test")
@DataJpaTest
@Import(JdbcAdminDashboardQueryRepository.class)
class JdbcAdminDashboardQueryRepositoryTest {

    @Autowired
    private AdminDashboardQueryRepository repository;

    @Autowired
    private EntityManager entityManager;

    @BeforeEach
    void createAiUsageTable() {
        entityManager.createNativeQuery("""
                CREATE TABLE IF NOT EXISTS user_daily_activities (
                    activity_date DATE NOT NULL,
                    user_id BIGINT NOT NULL,
                    first_active_at TIMESTAMP NOT NULL,
                    last_active_at TIMESTAMP NOT NULL,
                    used_observation BOOLEAN NOT NULL DEFAULT FALSE,
                    used_community BOOLEAN NOT NULL DEFAULT FALSE,
                    observation_created_count BIGINT NOT NULL DEFAULT 0,
                    observation_regenerated_count BIGINT NOT NULL DEFAULT 0,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    PRIMARY KEY (activity_date, user_id)
                )
                """).executeUpdate();
        entityManager.createNativeQuery("""
                CREATE TABLE IF NOT EXISTS user_lifecycle_events (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL,
                    event_type VARCHAR(30) NOT NULL,
                    had_meaningful_use BOOLEAN,
                    occurred_at TIMESTAMP NOT NULL,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """).executeUpdate();
        entityManager.createNativeQuery("""
                CREATE TABLE IF NOT EXISTS observation_generation_usages (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    correlation_id VARCHAR(36) NOT NULL,
                    user_id BIGINT NOT NULL,
                    operation VARCHAR(30) NOT NULL,
                    provider_status VARCHAR(30) NOT NULL,
                    business_status VARCHAR(30) NOT NULL,
                    model VARCHAR(100),
                    input_tokens BIGINT,
                    output_tokens BIGINT,
                    total_tokens BIGINT,
                    duration_ms BIGINT NOT NULL,
                    error_category VARCHAR(50),
                    occurred_at TIMESTAMP NOT NULL,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """).executeUpdate();
        entityManager.createNativeQuery("DELETE FROM observation_generation_usages").executeUpdate();
        entityManager.createNativeQuery("DELETE FROM user_daily_activities").executeUpdate();
        entityManager.createNativeQuery("DELETE FROM user_lifecycle_events").executeUpdate();
    }

    @Test
    void getObservationWritingCohortCountsEligibleUsersAndWritersWithinSevenCalendarDays() {
        insertSignup(1L, LocalDateTime.of(2026, 10, 1, 12, 0));
        insertSignup(2L, LocalDateTime.of(2026, 10, 2, 12, 0));
        insertSignup(3L, LocalDateTime.of(2026, 10, 7, 12, 0));
        insertSignup(4L, LocalDateTime.of(2026, 10, 8, 0, 0));
        insertObservationActivity(1L, LocalDate.of(2026, 10, 1), 1);
        insertObservationActivity(1L, LocalDate.of(2026, 10, 7), 2);
        insertObservationActivity(2L, LocalDate.of(2026, 10, 9), 1);
        insertObservationActivity(4L, LocalDate.of(2026, 10, 8), 1);

        var cohort = repository.getObservationWritingCohort(
                LocalDateTime.of(2026, 10, 1, 0, 0),
                LocalDateTime.of(2026, 10, 8, 0, 0)
        );

        assertThat(cohort.eligibleUsers()).isEqualTo(3);
        assertThat(cohort.writers()).isEqualTo(1);
    }

    @Test
    void getAiUsageDoesNotCountPendingCallsAsFailures() {
        insertUsage("saved", "SUCCESS", "SAVED");
        insertUsage("provider-failed", "FAILED", "PROVIDER_FAILED");
        insertUsage("persistence-failed", "SUCCESS", "PERSISTENCE_FAILED");
        insertUsage("pending", "SUCCESS", "PENDING");

        var totals = repository.getAiUsage(
                LocalDateTime.of(2026, 10, 25, 0, 0),
                LocalDateTime.of(2026, 10, 26, 0, 0)
        );

        assertThat(totals.calls()).isEqualTo(4);
        assertThat(totals.successes()).isEqualTo(1);
        assertThat(totals.failures()).isEqualTo(2);
    }

    private void insertUsage(String correlationId, String providerStatus, String businessStatus) {
        entityManager.createNativeQuery("""
                        INSERT INTO observation_generation_usages(
                            correlation_id, user_id, operation, provider_status, business_status,
                            duration_ms, occurred_at
                        ) VALUES (:correlationId, 1, 'CREATE', :providerStatus, :businessStatus, 100, :occurredAt)
                        """)
                .setParameter("correlationId", correlationId)
                .setParameter("providerStatus", providerStatus)
                .setParameter("businessStatus", businessStatus)
                .setParameter("occurredAt", LocalDateTime.of(2026, 10, 25, 12, 0))
                .executeUpdate();
    }

    private void insertSignup(long userId, LocalDateTime occurredAt) {
        entityManager.createNativeQuery("""
                        INSERT INTO user_lifecycle_events(user_id, event_type, occurred_at)
                        VALUES (:userId, 'SIGNUP', :occurredAt)
                        """)
                .setParameter("userId", userId)
                .setParameter("occurredAt", occurredAt)
                .executeUpdate();
    }

    private void insertObservationActivity(long userId, LocalDate activityDate, long createdCount) {
        LocalDateTime activeAt = activityDate.atTime(12, 0);
        entityManager.createNativeQuery("""
                        INSERT INTO user_daily_activities(
                            activity_date, user_id, first_active_at, last_active_at,
                            observation_created_count
                        ) VALUES (:activityDate, :userId, :activeAt, :activeAt, :createdCount)
                        """)
                .setParameter("activityDate", activityDate)
                .setParameter("userId", userId)
                .setParameter("activeAt", activeAt)
                .setParameter("createdCount", createdCount)
                .executeUpdate();
    }
}
