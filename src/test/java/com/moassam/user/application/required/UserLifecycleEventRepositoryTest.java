package com.moassam.user.application.required;

import com.moassam.user.domain.UserLifecycleEventType;
import jakarta.persistence.EntityManager;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.orm.jpa.DataJpaTest;
import org.springframework.test.context.ActiveProfiles;

import java.time.LocalDateTime;

import static org.assertj.core.api.Assertions.assertThat;

@ActiveProfiles("test")
@DataJpaTest
class UserLifecycleEventRepositoryTest {

    @Autowired
    private UserLifecycleEventRepository repository;

    @Autowired
    private EntityManager entityManager;

    @BeforeEach
    void createAnalyticsTable() {
        entityManager.createNativeQuery("""
                CREATE TABLE IF NOT EXISTS user_lifecycle_events (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL,
                    event_type VARCHAR(30) NOT NULL,
                    had_meaningful_use BOOLEAN,
                    occurred_at TIMESTAMP NOT NULL,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """).executeUpdate();
        entityManager.createNativeQuery("DELETE FROM user_lifecycle_events").executeUpdate();
    }

    @Test
    void append_preservesRepeatedLifecycleEvents() {
        LocalDateTime first = LocalDateTime.of(2026, 10, 20, 10, 0);
        LocalDateTime second = LocalDateTime.of(2026, 10, 25, 11, 0);

        repository.append(7L, UserLifecycleEventType.WITHDRAWAL.name(), false, first);
        repository.append(7L, UserLifecycleEventType.REACTIVATION.name(), null, second);
        entityManager.flush();

        Number count = (Number) entityManager.createNativeQuery("""
                        SELECT COUNT(*) FROM user_lifecycle_events WHERE user_id = 7
                        """)
                .getSingleResult();

        assertThat(count.longValue()).isEqualTo(2L);
    }
}
